import assert from 'node:assert/strict';
import { join } from 'node:path';
import { test } from 'node:test';

import * as claude from '../agents/claude-code.js';
import { assemble } from '../lib/assemble.js';
import { resolveProject } from '../lib/project.js';
import { fixtureContext, tempDir, writeTree } from './helpers.js';

const ID = '11111111-2222-4333-8444-555555555555';
const STUB = '99999999-2222-4333-8444-555555555555';
const OTHER = '77777777-2222-4333-8444-555555555555';

function chain(type, ts, extra) {
  return { type, timestamp: ts, sessionId: ID, cwd: extra.cwd, gitBranch: 'feature/x', isSidechain: false, uuid: `${type}-${ts}`, ...extra };
}

function fixture() {
  const home = tempDir('copass-home-');
  const projectDir = join(tempDir('copass-proj-'), 'my_app.v2'); // '_' and '.' are lossy in Claude's encoding
  writeTree(projectDir, { 'README.md': 'x' });
  const dir = `.claude/projects/${claude.sanitize(projectDir)}`;
  const cwd = projectDir;
  const t = (m) => new Date(Date.UTC(2026, 9, 25, 9, m)).toISOString();
  writeTree(home, {
    [`${dir}/${ID}.jsonl`]: [
      { type: 'queue-operation', operation: 'enqueue', content: 'ignored, dequeued later', timestamp: t(0) },
      { type: 'queue-operation', operation: 'dequeue', timestamp: t(0) },
      chain('user', t(1), { cwd, message: { role: 'user', content: [{ type: 'text', text: '<ide_opened_file>a.ts</ide_opened_file>' }, { type: 'text', text: "Fix the parser. Don't change the API." }] } }),
      chain('user', t(1), { cwd, isMeta: true, message: { role: 'user', content: 'Caveat: generated by local commands' } }),
      chain('assistant', t(2), { cwd, message: { id: 'm1', model: 'claude-opus-5-5', stop_reason: 'tool_use', content: [{ type: 'text', text: 'Looking at the parser.' }] } }),
      chain('assistant', t(2), { cwd, message: { id: 'm1', model: 'claude-opus-5-5', stop_reason: 'tool_use', content: [{ type: 'tool_use', id: 'tu1', name: 'Edit', input: { file_path: `${cwd}/parser.js` } }] } }),
      chain('assistant', t(3), { cwd, message: { id: 'm2', model: 'claude-opus-5-5', content: [{ type: 'tool_use', id: 'tu2', name: 'Bash', input: { command: 'npm test' } }] } }),
      chain('user', t(3), { cwd, toolUseResult: { stderr: 'boom' }, sourceToolAssistantUUID: 'x', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'tu2', is_error: true, content: '1 test failed: parser.spec.js' }] } }),
      chain('assistant', t(4), { cwd, message: { id: 'm3', model: 'claude-opus-5-5', content: [{ type: 'tool_use', id: 'tu3', name: 'TodoWrite', input: { todos: [{ content: 'fix tokenizer', status: 'completed' }, { content: 'fix tests', status: 'in_progress' }] } }] } }),
      chain('system', t(5), { cwd, subtype: 'compact_boundary', compactMetadata: { trigger: 'auto', preTokens: 900000 } }),
      chain('user', t(5), { cwd, isCompactSummary: true, isVisibleInTranscriptOnly: true, message: { role: 'user', content: 'This session is being continued from a previous conversation that ran out of context.\n\nSummary:\n1. Primary Request: fix the parser\n\nPlease continue the conversation from where we left off without asking the user any further questions. Continue with the last task.' } }),
      chain('user', t(6), { cwd, message: { role: 'user', content: '<command-name>/model</command-name>\n<command-args>opus</command-args>' } }),
      chain('assistant', t(7), { cwd, isSidechain: true, message: { id: 'side', content: [{ type: 'text', text: 'subagent noise' }] } }),
      chain('user', t(8), { cwd, message: { role: 'user', content: 'Now also handle unicode identifiers' } }),
      chain('assistant', t(9), { cwd, isApiErrorMessage: true, error: 'rate_limit', apiErrorStatus: 429, message: { model: '<synthetic>', content: [{ type: 'text', text: "You've hit your session limit · resets 2pm (Pacific/Auckland)" }] } }),
      { type: 'queue-operation', operation: 'enqueue', content: '<task-notification>background job finished</task-notification>', timestamp: t(10) },
      { type: 'queue-operation', operation: 'enqueue', timestamp: t(10) },
      { type: 'queue-operation', operation: 'dequeue', timestamp: t(10) },
      { type: 'queue-operation', operation: 'dequeue', timestamp: t(10) },
      { type: 'queue-operation', operation: 'enqueue', content: 'and update the README', timestamp: t(10) },
      { type: 'custom-title', customTitle: 'Parser fixes', sessionId: ID },
    ],
    [`${dir}/${STUB}.jsonl`]: [{ type: 'ai-title', aiTitle: 'stub only', sessionId: STUB }],
    // A sibling like ".../my_app.v2-backup" shares the name prefix; its recorded cwd rules it out.
    [`.claude/projects/${claude.sanitize(`${projectDir}-backup`)}/${OTHER}.jsonl`]: [chain('user', t(1), { cwd: `${projectDir}-backup`, message: { role: 'user', content: 'hi' } })],
  });
  return { home, projectDir };
}

test('sanitize matches Claude Code, including the 200-char hash suffix', () => {
  assert.equal(claude.sanitize('/Users/me/my_app.v2'), '-Users-me-my-app-v2');
  const long = `/Users/me/${'a'.repeat(250)}`;
  const name = claude.sanitize(long);
  assert.equal(name.length > 200 && name.startsWith('-Users-me-aaa'), true);
  assert.match(name, /^.{200}-[0-9a-z]+$/);
});

test('finds the real session, skips stubs and unrelated dirs, flags the running one', async () => {
  const { home, projectDir } = fixture();
  const project = resolveProject(projectDir);
  const found = await claude.findSessions(project, fixtureContext(home));
  assert.deepEqual(found.map((c) => c.id), [ID]);
  assert.equal(found[0].title, 'Parser fixes');
  assert.equal(found[0].score, 3);
  assert.equal(found[0].lastActivity, Date.UTC(2026, 9, 25, 9, 8), 'activity = last real message, not the error or metadata');

  const self = await claude.findSessions(project, fixtureContext(home, { CLAUDE_CODE_SESSION_ID: ID }));
  assert.equal(self[0].current, true);
});

test('loads prompts, tools, plan, compaction, stop and queued prompts', async () => {
  const { home, projectDir } = fixture();
  const ctx = fixtureContext(home);
  const [candidate] = await claude.findSessions(resolveProject(projectDir), ctx);
  const { meta, events } = await claude.loadSession(candidate, ctx);
  const s = assemble(meta, events);

  assert.deepEqual(s.prompts.map((p) => p.text), ["Fix the parser. Don't change the API.", '/model opus', 'Now also handle unicode identifiers']);
  assert.equal(s.latest.started, false);
  assert.deepEqual(s.latest.queued.map((q) => q.text), ['and update the README']);
  assert.equal(s.stop.reason, 'quota');
  assert.match(s.compaction.summary, /^Summary:/);
  assert.doesNotMatch(s.compaction.summary, /continue the conversation/i, "the summary's order to the old model is dropped");
  assert.equal(s.compaction.trigger, 'auto');
  assert.deepEqual(s.files.map((f) => f.path), [`${projectDir}/parser.js`]);
  assert.equal(s.failures[0].error, '1 test failed: parser.spec.js');
  assert.deepEqual(s.plan.items.map((i) => i.status), ['done', 'active']);
  assert.equal(meta.branch, 'feature/x');
  assert.equal(meta.model, 'claude-opus-5-5');
  assert.equal(meta.resumeCommand, `claude --resume ${ID}`);
  assert.ok(!events.some((e) => e.text === 'subagent noise'));
});
